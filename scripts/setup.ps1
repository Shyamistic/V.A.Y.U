param([switch]$Rebuild)
$ErrorActionPreference = 'Stop'
$product = Split-Path -Parent $PSScriptRoot
$workspace = Split-Path -Parent $product
$python = Join-Path $workspace '.venv\Scripts\python.exe'
$target = Join-Path $product 'runtime\site-packages'
$lock = Join-Path $product 'requirements.lock'
if (-not (Test-Path -LiteralPath $product)) { throw "Product root is missing" }
if (-not (Test-Path -LiteralPath $python)) { throw "Supplied executor is missing: $python" }
if (-not (Test-Path -LiteralPath $lock)) { throw "requirements.lock is missing" }
$baseline = Join-Path $product 'runtime\provenance\protected_manifest_before.json'
$env:PYTHONPATH = "$(Join-Path $product 'src');$(Join-Path $product 'runtime\site-packages')"
if (-not (Test-Path -LiteralPath $baseline)) {
  & (Join-Path $product 'scripts\discover_vayu_assets.ps1') -Output $baseline
  if ($LASTEXITCODE -ne 0) { throw "protected-input baseline inventory failed" }
}
if ($Rebuild -and (Test-Path -LiteralPath $target)) {
  Remove-Item -LiteralPath $target -Recurse -Force
}
New-Item -ItemType Directory -Path $target -Force | Out-Null
$manifest = Join-Path $product 'runtime\install-manifest.json'
$lockHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $lock).Hash.ToLowerInvariant()
if ((Get-ChildItem -LiteralPath $target -Force | Measure-Object).Count -gt 0 -and -not (Test-Path -LiteralPath $manifest)) {
  throw "site-packages is non-empty without a matching install manifest; rerun with -Rebuild"
}
$match = $false
if ((Test-Path -LiteralPath $manifest) -and -not $Rebuild) {
  try { $match = ((Get-Content -Raw -LiteralPath $manifest | ConvertFrom-Json).lock_sha256 -eq $lockHash) } catch { $match = $false }
}
if (-not $match) {
  $hasHashes = (Get-Content -LiteralPath $lock | Select-String -Pattern '--hash=sha256:' -Quiet)
  if ($hasHashes) {
    & $python -m pip install --no-deps --require-hashes --target $target -r $lock
  } else {
    # The checked-in bootstrap lock is pinned but hash material is generated by
    # the product-owned install manifest on this isolated machine.
    & $python -m pip install --target $target -r $lock
  }
  if ($LASTEXITCODE -ne 0) { throw "dependency installation failed; no .venv mutation was attempted" }
}
& $python (Join-Path $product 'scripts\write_install_manifest.py') $product $target $lock
if ($LASTEXITCODE -ne 0) { throw "install manifest verification failed" }
Write-Output "MonsoonGrid dependencies installed only at $target"
