#!/usr/bin/env python3
"""Cost model generator (design §11, FR-D1/D2, AC-42).

Reads deploy/cost/pricing-inputs.json and writes docs/cost-model.md so the
arithmetic in the doc is reproducible and the prices are data, not prose.

Refuses to emit a total unless every line item carries a `status`. Renders every
ASSUMPTION-UNVERIFIED price with a visible marker. Emits the quantity-derivation
table, the dominant-cost-driver conclusion, and the two sensitivity tables.
"""

from __future__ import annotations

import json
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_REPO = _HERE.parent.parent
_PRICING = _HERE / "pricing-inputs.json"
_OUT = _REPO / "docs" / "cost-model.md"

SECONDS_PER_MONTH = 2_629_440  # 30.44 days
DECISIONS_PER_DAY = 96
DECISIONS_PER_MONTH = round(96 * 30.44)


def _load() -> dict:
    data = json.loads(_PRICING.read_text(encoding="utf-8"))
    for name, item in data["line_items"].items():
        if "status" not in item:
            raise SystemExit(f"line item {name} has no status; refusing to emit a total")
    return data


def _price_row(name: str, item: dict) -> str:
    marker = " **(ASSUMPTION-UNVERIFIED)**" if item["status"] != "verified" else ""
    retrieved = item.get("retrieved_utc") or "not retrieved"
    return f"| `{name}` | {item['value']} | {item['unit']} | {retrieved} | [source]({item['source_url']}){marker} |"


def render(data: dict) -> str:
    items = data["line_items"]
    lines: list[str] = []
    out = lines.append

    out("# MonsoonGrid pilot cost model")
    out("")
    out("> Generated by `deploy/cost/cost_model.py` from `deploy/cost/pricing-inputs.json`. "
        "Regenerate after editing prices. This is an estimate, not a quote.")
    out("")
    out("## Honesty constraint (ASM-6)")
    out("")
    out("No web retrieval tool was available when this model was built, so published "
        "Google Cloud list prices could not be fetched here. Every unit price below ships "
        "with a source URL and a `status`; prices marked **ASSUMPTION-UNVERIFIED** are not "
        "defensible until the implementation phase retrieves the list price and flips the "
        "status. Two facts are structural, not numeric, and are stated as verified:")
    out("")
    for fact in data.get("structural_facts", []):
        out(f"- {fact}")
    out("")

    out("## Unit prices")
    out("")
    out("| Line item | Unit price | Unit | Retrieved (UTC) | Source |")
    out("|---|---|---|---|---|")
    for name, item in items.items():
        out(_price_row(name, item))
    out("")

    out("## Quantity derivation (fully determined; independent of prices)")
    out("")
    out("| Driver | Derivation | Value |")
    out("|---|---|---|")
    out(f"| Decisions per day | 96 slots x 1 portfolio | {DECISIONS_PER_DAY} |")
    out(f"| Decisions per month | 96 x 30.44 | {DECISIONS_PER_MONTH} |")
    out("| Fast-loop requests/month | = decisions/month | 2922 |")
    out("| Slow-loop requests/month | 1/day x 30.44 | 30 |")
    out("| Operator/API reads/month | 2 operators x ~330/day (ASSUMPTION) | 20000 |")
    out("| Billable active request-seconds | fast 2922x45s + slow 30x200s + reads 20000x0.15s | 140578 |")
    out(f"| Idle instance-seconds (minScale:1) | {SECONDS_PER_MONTH} total - 140578 active | 2488862 |")
    out("| Certificates stored/month | 2922 x ~28 KB (measured runtime/artifacts) | ~82 MB; ~2.9 GB/3yr |")
    out("| Evidence objects/month | 2922 x ~9 objects x ~3.3 KB (measured runtime/store) | ~87 MB; ~3.1 GB/3yr |")
    out("| BigQuery rows | 96 x 30.44 x 36 months | ~105200 rows; ~210 MB/3yr |")
    out("| Audit records/month | approvals + denials + aggregated rate-limits (ASSUMPTION) | ~15000; ~10 MB |")
    out("")

    out("## Dominant cost driver")
    out("")
    out("The dominant cost is structural and independent of exact prices: **the always-on "
        "Cloud SQL instance plus the `minScale: 1` idle Cloud Run instance**. Both are "
        "time-billed regardless of traffic, while every other line item is volume-billed "
        "against small volumes. 2922 decisions/month is a trivially small workload; three "
        "years of 15-minute history is ~210 MB in BigQuery; evidence storage is ~6 GB. The "
        "pilot bill is set by always-on floors, not by decision volume. The two levers that "
        "matter: (a) whether `minScale: 1` is genuinely required, and (b) whether Cloud SQL "
        "can be deferred until the Postgres migration actually lands.")
    out("")

    out("## Sensitivity: portfolio count")
    out("")
    out("| Portfolio count | Decisions/month | Active request-seconds | Evidence GB/3yr | BigQuery GB/3yr |")
    out("|---|---|---|---|---|")
    out("| 1 | 2922 | 140578 | 6.0 | 0.21 |")
    out("| 5 | 14610 | ~660000 | 30 | 1.05 |")
    out("| 20 | 58440 | ~2630000 | 120 | 4.2 |")
    out("| 50 | 146100 | ~6580000 | 300 | 10.5 |")
    out("")
    out("At 20+ portfolios the active request-seconds exceed the idle seconds and Cloud Run "
        "becomes traffic-dominated, which is where `minScale` stops mattering and "
        "`containerConcurrency`/vCPU sizing start to.")
    out("")

    out("## Sensitivity: retention period")
    out("")
    out("| Retention | BigQuery GB | GCS evidence GB | Note |")
    out("|---|---|---|---|")
    out("| 1 year | 0.07 | 2.0 | |")
    out("| 3 years | 0.21 | 6.0 | the stated pilot target |")
    out("| 7 years | 0.49 | 14.0 | BigQuery long-term storage rate applies after 90 days untouched |")
    out("")
    out("Three-year retention is never a material cost at any portfolio count in this range, "
        "so retention should be chosen for evidentiary value rather than for cost.")
    out("")

    unverified = sum(1 for i in items.values() if i["status"] != "verified")
    out("## Total")
    out("")
    out(f"A monthly total is intentionally NOT asserted here: {unverified} of {len(items)} unit "
        "prices are still ASSUMPTION-UNVERIFIED. The dry-run provisioning plan "
        "(`deploy/provision.ps1`) prints a per-resource estimate and a running total from these "
        "same inputs; treat that total as indicative until the prices are retrieved and flipped.")
    out("")
    return "\n".join(lines) + "\n"


def main() -> int:
    data = _load()
    _OUT.parent.mkdir(parents=True, exist_ok=True)
    _OUT.write_text(render(data), encoding="utf-8")
    print(f"wrote {_OUT.relative_to(_REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
